/** Headless contract tests. Expected domain results are generated by the pinned web model. */
public final class CoreContractTest {
    private static int scenarios;
    private static int operations;

    public static void main(String[] args) throws Exception {
        if (args.length != 1) throw new IllegalArgumentException("Pass tests/fixtures/voxel-contract.json");
        JSONObject fixture = new JSONObject(new String(Files.readAllBytes(new File(args[0]).toPath()), StandardCharsets.UTF_8));
        testGoldenContract(fixture);
        testSnapshotsAndInitialization();
        testConcurrentSnapshots();
        testCodec();
        testStorage();
        System.out.println("PASS: " + scenarios + " legacy JS scenarios, " + operations
                + " operations; strict JSON, immutable/concurrent snapshots, atomic storage, backups and recovery.");
    }

    private static void testGoldenContract(JSONObject fixture) throws Exception {
        JSONObject rules = fixture.getJSONObject("rules");
        check(VoxelWorld.SIZE == rules.getInt("size"), "SIZE");
        check(VoxelWorld.HEIGHT == rules.getInt("height"), "HEIGHT");
        check(VoxelWorld.MAX_BLOCKS == rules.getInt("maxBlocks"), "MAX_BLOCKS");
        check(VoxelWorld.HISTORY_LIMIT == rules.getInt("historyLimit"), "HISTORY_LIMIT");
        JSONArray materials = fixture.getJSONArray("materials");
        check(materials.length() == VoxelWorld.materials().size(), "material count");
        for (int i = 0; i < materials.length(); i++) {
            JSONObject item = materials.getJSONObject(i);
            VoxelWorld.Material actual = VoxelWorld.materials().get(i);
            check(actual.id.equals(item.getString("id")), "material id");
            check(actual.label.equals(item.getString("label")), "material label");
            int color = (int) (0xff000000L | Long.parseLong(item.getString("color").substring(1), 16));
            check(actual.color == color, "material color");
        }
        JSONArray tests = fixture.getJSONArray("cases");
        for (int c = 0; c < tests.length(); c++) {
            JSONObject item = tests.getJSONObject(c);
            String id = item.getString("id");
            VoxelWorld world = new VoxelWorld();
            JSONArray steps = item.getJSONArray("steps");
            for (int i = 0; i < steps.length(); i++) {
                JSONObject step = steps.getJSONObject(i);
                Object result = execute(world, step.getString("operation"), step.getJSONArray("args"));
                sameJson(result, step.get("expectedResult"), id + " step " + i + " result");
                JSONObject state = step.getJSONObject("expectedState");
                check(world.count() == state.getInt("count"), id + " count at " + i);
                check(world.revision() == state.getLong("revision"), id + " revision at " + i);
                check(world.canUndo() == state.getBoolean("canUndo"), id + " undo at " + i);
                check(world.canRedo() == state.getBoolean("canRedo"), id + " redo at " + i);
                operations++;
            }
            sameJson(blocksJson(world.blocks()), item.getJSONArray("expectedBlocks"), id + " final blocks");
            JSONObject progress = item.getJSONObject("expectedProgress");
            for (String mission : Arrays.asList("free", "tower", "stairs", "bridge", "symmetry", "unknown-mission"))
                sameJson(progressJson(world.progress(mission)), progress.getJSONObject(mission), id + " " + mission);
            scenarios++;
        }
    }

    private static Object execute(VoxelWorld world, String operation, JSONArray args) throws Exception {
        switch (operation) {
            case "add": return world.add(args.getInt(0), args.getInt(1), args.getInt(2), args.getString(3));
            case "remove": return world.remove(args.getInt(0), args.getInt(1), args.getInt(2));
            case "move": {
                JSONObject from = args.getJSONObject(0), to = args.getJSONObject(1);
                return world.move(from.getInt("x"), from.getInt("y"), from.getInt("z"),
                        to.getInt("x"), to.getInt("y"), to.getInt("z"));
            }
            case "clear": return world.clear();
            case "undo": return world.undo();
            case "redo": return world.redo();
            case "has": return world.has(args.getInt(0), args.getInt(1), args.getInt(2));
            case "canPlace": return world.canPlace(args.getInt(0), args.getInt(1), args.getInt(2));
            case "get": return blockJson(world.get(args.getInt(0), args.getInt(1), args.getInt(2)));
            case "progress": return progressJson(world.progress(args.getString(0)));
            case "load":
                try {
                    Object input = args.get(0);
                    String json = input instanceof String ? (String) input : input.toString();
                    return world.load(ProjectCodec.decodeImport(json).blocks);
                } catch (ProjectCodec.ProjectFormatException error) { return false; }
            default: throw new AssertionError("Unknown fixture operation: " + operation);
        }
    }

    private static void testSnapshotsAndInitialization() {
        VoxelWorld world = new VoxelWorld();
        world.add(0, 0, 0, "grass");
        List<VoxelWorld.Block> snapshot = world.blocks();
        world.add(1, 0, 0, "wood");
        check(snapshot.size() == 1, "snapshot must not be live");
        boolean immutable = false;
        try { snapshot.clear(); } catch (UnsupportedOperationException expected) { immutable = true; }
        check(immutable, "snapshot must be immutable");
        world.undo();
        check(world.canRedo(), "setup redo");
        long before = world.revision();
        check(!world.initialize(Arrays.asList(new VoxelWorld.Block(0,0,0,"grass"), new VoxelWorld.Block(0,0,0,"wood"))), "invalid initialization");
        check(world.canRedo() && world.revision() == before && world.count() == 1, "invalid initialization preserves history");
        check(world.initialize(Collections.singletonList(new VoxelWorld.Block(7,5,7,"crystal"))), "initialize valid");
        check(!world.canUndo() && !world.canRedo() && world.has(7,5,7), "opening project clears old history");
        check(world.goals("missing").isEmpty(), "unknown mission has no goal");
    }

    private static void testConcurrentSnapshots() throws Exception {
        final VoxelWorld world = new VoxelWorld();
        final AtomicReference<Throwable> error = new AtomicReference<>();
        Thread writer = new Thread(() -> {
            try { for (int i = 0; i < 3000; i++) { world.add(0,0,0,"stone"); world.remove(0,0,0); } }
            catch (Throwable failure) { error.set(failure); }
        });
        Thread renderer = new Thread(() -> {
            try {
                for (int i = 0; i < 3000; i++) {
                    List<VoxelWorld.Block> snapshot = world.blocks();
                    check(snapshot.size() <= 1 && VoxelWorld.validBlocks(snapshot), "concurrent snapshot integrity");
                    for (VoxelWorld.Block block : snapshot) check(block.material.equals("stone"), "immutable concurrent block");
                }
            } catch (Throwable failure) { error.set(failure); }
        });
        writer.start(); renderer.start(); writer.join(); renderer.join();
        if (error.get() != null) throw new AssertionError("Concurrent model access failed", error.get());
    }

    private static void testCodec() throws Exception {
        String legacy = "{\"version\":1,\"blocks\":[{\"x\":3,\"y\":5,\"z\":3,\"material\":\"wood\"}]}";
        ProjectCodec.Project first = ProjectCodec.decodeImport(legacy);
        check(first.blocks.size() == 1 && first.blocks.get(0).y == 5, "legacy unsupported blocks preserved");
        String encoded = ProjectCodec.encode(first);
        ProjectCodec.Project stored = ProjectCodec.decodeStored(encoded, first.projectId);
        check(stored.projectId.equals(first.projectId) && stored.blocks.equals(first.blocks), "stored round-trip");
        ProjectCodec.Project second = ProjectCodec.decodeImport(encoded);
        check(!second.projectId.equals(first.projectId), "every import receives a new ID");
        JSONObject unsafe = new JSONObject(encoded);
        unsafe.put("projectId", "../../outside");
        unsafe.put("updatedAt", "untrusted");
        ProjectCodec.Project imported = ProjectCodec.decodeImport(unsafe.toString());
        check(ProjectCodec.isProjectId(imported.projectId), "imported path-like ID ignored");
        expectFormat(() -> ProjectCodec.decodeStored(encoded, second.projectId), "stored identity mismatch");
        expectFormat(() -> ProjectCodec.decodeStored(unsafe.toString()), "invalid stored identity");
        for (String invalid : Arrays.asList("", "null", "true", "[]", "{version:1,blocks:[]}",
                "/*x*/{\"version\":1,\"blocks\":[]}", "{\"version\":1,\"blocks\":[,]}",
                "{\"version\":1,\"blocks\":[]}x", "{\"version\":true,\"blocks\":[]}",
                "{\"version\":\"1\",\"blocks\":[]}", "{\"version\":1,\"blocks\":[{\"x\":0,\"z\":0,\"material\":\"stone\"}]}"))
            expectFormat(() -> ProjectCodec.decodeImport(invalid), "strict JSON: " + invalid);
        String base = "{\"version\":1,\"blocks\":[]}";
        char[] padding = new char[ProjectCodec.MAX_JSON_CHARS - base.length()];
        Arrays.fill(padding, ' ');
        String boundary = base + new String(padding);
        check(ProjectCodec.decodeImport(boundary).blocks.isEmpty(), "60000 character boundary accepted");
        expectFormat(() -> ProjectCodec.decodeImport(boundary + " "), "oversized JSON rejected");
        ProjectCodec.Project renamed = ProjectCodec.update(first, "Minha ponte", "bridge", first.blocks);
        check(renamed.projectId.equals(first.projectId) && renamed.name.equals("Minha ponte")
                && renamed.updatedAt > first.updatedAt, "rename keeps identity and advances local timestamp");
    }

    private static void testStorage() throws Exception {
        Path temporary = Files.createTempDirectory("tv-touch-project-store-");
        try {
            ProjectStore store = new ProjectStore(temporary.toFile());
            VoxelWorld world = new VoxelWorld();
            world.add(0,0,0,"grass");
            ProjectCodec.Project one = ProjectCodec.create("Torre", "tower", world.blocks());
            store.save(one);
            check(store.list().size() == 1 && !store.load(one.projectId).recovered, "first explicit save");
            world.add(0,1,0,"wood");
            ProjectCodec.Project two = ProjectCodec.update(one, "Torre", "tower", world.blocks());
            store.save(two);
            File directory = new File(temporary.toFile(), "projects");
            File main = new File(directory, one.projectId + ".json");
            File previous = new File(directory, one.projectId + ".previous.json");
            check(store.load(one.projectId).project.blocks.size() == 2 && previous.isFile(), "second save keeps previous");

            Files.write(main.toPath(), "{".getBytes(StandardCharsets.UTF_8));
            ProjectStore.LoadResult recovered = store.load(one.projectId);
            check(recovered.recovered && recovered.warning != null && recovered.project.blocks.size() == 1, "valid backup fallback is explicit");
            check(new String(Files.readAllBytes(main.toPath()), StandardCharsets.UTF_8).equals("{"), "load does not silently rewrite corruption");
            check(store.list().get(0).recovered, "list reports recovered state");
            store.recover(one.projectId);
            check(!store.load(one.projectId).recovered && store.load(one.projectId).project.blocks.size() == 1, "explicit recovery commits backup");
            store.save(two);

            File blockedCandidate = new File(main.getPath() + ".tmp");
            check(blockedCandidate.mkdir(), "create write failure fixture");
            Files.write(new File(blockedCandidate, "keep").toPath(), new byte[]{1});
            expectIo(() -> store.save(one), "failed temporary write");
            check(store.load(one.projectId).project.blocks.size() == 2, "failed write preserves committed project");
            Files.delete(new File(blockedCandidate, "keep").toPath());
            Files.delete(blockedCandidate.toPath());
            Files.write(blockedCandidate.toPath(), "partial".getBytes(StandardCharsets.UTF_8));
            check(store.load(one.projectId).project.blocks.size() == 2, "interrupted temp is never treated as committed");
            Files.delete(blockedCandidate.toPath());

            store.saveRecovery(two);
            check(store.list().size() == 1, "recovery is not an explicit saved project");
            check(store.loadRecovery().project.blocks.size() == 2, "recovery draft round-trip");
            world.add(0,2,0,"ice");
            ProjectCodec.Project draft = ProjectCodec.update(two, "Rascunho", "tower", world.blocks());
            store.saveRecovery(draft);
            Files.write(new File(directory, "recovery.json").toPath(), "bad".getBytes(StandardCharsets.UTF_8));
            check(store.loadRecovery().recovered && store.loadRecovery().project.blocks.size() == 2, "recovery slot has its own backup");
            check(store.load(one.projectId).project.blocks.size() == 2, "automatic recovery never overwrites explicit save");
            store.clearRecovery();
            check(store.loadRecovery() == null && store.list().size() == 1, "clear recovery preserves explicit save");

            ProjectCodec.Project other = ProjectCodec.create("Outro", "free", Collections.<VoxelWorld.Block>emptyList());
            Files.write(main.toPath(), "bad".getBytes(StandardCharsets.UTF_8));
            Files.write(previous.toPath(), ProjectCodec.encode(other).getBytes(StandardCharsets.UTF_8));
            expectIo(() -> store.load(one.projectId), "foreign backup identity rejected");
            check(store.list().get(0).corrupt && main.exists() && previous.exists(), "unreadable projects remain visible and retained");
            Files.write(previous.toPath(), ProjectCodec.encode(one).getBytes(StandardCharsets.UTF_8));
            Files.delete(main.toPath());
            check(store.list().size() == 1 && store.list().get(0).recovered, "backup-only project is discoverable");
            store.save(two);
            Files.write(main.toPath(), new byte[]{(byte) 0xc3, (byte) 0x28});
            check(store.load(one.projectId).recovered, "malformed UTF-8 falls back to valid backup");
            expectIo(() -> store.delete("../outside"), "path traversal ID rejected");
            check(store.delete(one.projectId) && store.list().isEmpty(), "delete removes current and previous versions");
            check(!store.delete(one.projectId), "delete missing project is a no-op");
        } finally {
            List<Path> paths = new ArrayList<>();
            try (java.util.stream.Stream<Path> stream = Files.walk(temporary)) { stream.forEach(paths::add); }
            Collections.sort(paths, Comparator.reverseOrder());
            for (Path path : paths) Files.deleteIfExists(path);
        }
    }

    private static JSONArray blocksJson(List<VoxelWorld.Block> input) throws Exception {
        List<VoxelWorld.Block> blocks = new ArrayList<>(input);
        Collections.sort(blocks, new Comparator<VoxelWorld.Block>() {
            @Override public int compare(VoxelWorld.Block a, VoxelWorld.Block b) {
                if (a.y != b.y) return Integer.compare(a.y, b.y);
                if (a.z != b.z) return Integer.compare(a.z, b.z);
                return Integer.compare(a.x, b.x);
            }
        });
        JSONArray array = new JSONArray();
        for (VoxelWorld.Block block : blocks) array.put(blockJson(block));
        return array;
    }

    private static Object blockJson(VoxelWorld.Block block) throws Exception {
        if (block == null) return JSONObject.NULL;
        return new JSONObject().put("x", block.x).put("y", block.y).put("z", block.z).put("material", block.material);
    }

    private static JSONObject progressJson(VoxelWorld.Progress progress) throws Exception {
        return new JSONObject().put("done", progress.done).put("total", progress.total).put("complete", progress.complete);
    }

    private static void sameJson(Object actual, Object expected, String message) {
        boolean okay;
        if (actual == null || actual == JSONObject.NULL) okay = expected == null || expected == JSONObject.NULL;
        else if (actual instanceof JSONObject && expected instanceof JSONObject) okay = ((JSONObject) actual).similar(expected);
        else if (actual instanceof JSONArray && expected instanceof JSONArray) okay = ((JSONArray) actual).similar(expected);
        else if (actual instanceof Number && expected instanceof Number)
            okay = Double.compare(((Number) actual).doubleValue(), ((Number) expected).doubleValue()) == 0;
        else okay = actual.equals(expected);
        if (!okay) throw new AssertionError(message + "\nexpected=" + expected + "\nactual=" + actual);
    }

    private interface FormatAction { void run() throws ProjectCodec.ProjectFormatException; }
    private interface IoAction { void run() throws IOException; }
    private static void expectFormat(FormatAction action, String message) throws Exception {
        try { action.run(); } catch (ProjectCodec.ProjectFormatException expected) { return; }
        throw new AssertionError("Expected invalid project: " + message);
    }
    private static void expectIo(IoAction action, String message) throws Exception {
        try { action.run(); } catch (IOException expected) { return; }
        throw new AssertionError("Expected I/O failure: " + message);
    }
    private static void check(boolean okay, String message) { if (!okay) throw new AssertionError(message); }
}
